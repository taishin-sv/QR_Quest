// プリセットの遊び方(mode)に合わせた文言。'search'=たからさがし / 'mission'=ミッションをクリアしてカードをもらう
export const MODES = { mission: 'ミッション', search: 'たからさがし' };

export function modeOf(p) {
  return p && p.mode === 'mission' ? 'mission' : 'search';
}

export function words(p) {
  const m = modeOf(p) === 'mission';
  return {
    mission: m,
    hint: m ? 'ミッション' : 'ヒント',
    appSub: m ? 'ミッションを クリアして カードを よみこもう' : 'QRをよみとって つぎのばしょを さがそう',
    stageCountLabel: m ? 'ミッションのかず（スタートを除く）' : 'ヒントのかず（スタートを除く）',
    stageCountNote: m
      ? '各ミッションのあとに よみこむカードのまい数を、下で決められます。カード自体はテーマに関係なく共通の連番です。「いんさつ」タブで必要な枚数だけ書き出せます。'
      : '各ヒントごとに、あつめるカードのまい数を下で決められます。カード自体はテーマに関係なく共通の連番です。「いんさつ」タブで必要な枚数だけ書き出せます。',
    editTitle: m ? '📝 ミッションをつくる' : '📝 ヒントをつくる',
    editDesc: m
      ? '「START」はさいしょのミッション。ミッションをクリアしたら、親がカードをわたして読み込ませます。さいごの番号は「ゴールメッセージ」になります。'
      : '「0」はスタート直後のヒント。さいごの番号は「ゴールメッセージ」になります。',
    rowStart: (next) => (m ? 'さいしょのミッション（クリアしたら：' + next + ' をもらう）' : 'スタート直後のヒント（つぎ：' + next + ' をさがす）'),
    rowMid: (cur, next) =>
      m
        ? cur + ' を読み込んだあとのミッション（クリアしたら：' + next + ' をもらう）'
        : cur + ' を見つけたときのヒント（つぎ：' + next + ' をさがす）',
    rowGoal: (cur) => (m ? 'ゴールメッセージ（' + cur + ' を読み込んだとき）' : 'ゴールメッセージ（' + cur + ' を見つけたとき）'),
    countLabel: m ? 'よみこむカード：' : 'このヒントを もらうのに あつめるカード：',
    placeholder: (isGoal) => (isGoal ? 'れい：やったー！ぜんぶ クリアしたね！' : m ? 'れい：ジャンプを 10かい しよう！' : 'れい：つめたいところをさがしてね'),
    scanTitle: (g) => (m ? (g > 1 ? 'よみこむ カード（ぜんぶで ' + g + 'まい）' : 'よみこむ カード') : g > 1 ? 'いま さがす カード（ぜんぶで ' + g + 'まい）' : 'いま さがす カード'),
    nextLabel: (multi) =>
      m ? (multi ? 'クリアしたら この カードを ぜんぶ もらおう' : 'クリアしたら この カードを もらおう') : multi ? 'つぎは この カードを ぜんぶ さがそう' : 'つぎは この カードを さがそう',
    fallbackText: m ? 'つぎの ミッションに ちょうせん！' : 'つぎのばしょを さがしてみよう！',
    wrongStage: (n, want) => '#' + n + (m ? ' は まだ だよ。' + want + ' を よみこんでね' : ' は まだ だよ。' + want + ' を さがしてね'),
    dup: (n) => '#' + n + (m ? ' は もう ゲットしてるよ' : ' は もうみつけてるよ'),
    found: (n, rest) => '✅ #' + n + (m ? ' ゲット！ のこり' : ' みつけた！ のこり') + rest + 'まい',
    got: m ? '✅ ゲット！' : '✅ みつけた！',
    metaUnit: m ? 'ミッション' : 'ヒント',
  };
}
