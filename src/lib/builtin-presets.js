// プリセットの「中身」の署名。編集されたかどうかの判定に使う（名前・アイコン・各ミッションの絵文字/文章/枚数）。
// 枚数は未指定なら1枚として数える(旧形式の読み込み直後と揃えるため)。
export function contentSig(p) {
  return JSON.stringify([p.name, p.icon, (p.hints || []).map((h, i) => [h.emoji, h.text, i === 0 ? 0 : h.cardCount || 1])]);
}
const sigOf = (name, icon, items) => contentSig({ name, icon, hints: items.map(([emoji, text]) => ({ emoji, text })) });

