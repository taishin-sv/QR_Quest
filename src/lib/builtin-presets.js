// アプリに最初から入っているテーマ別プリセット。category の順に一覧へ並ぶ。
// hints[0]=さいしょのミッション(スタートカードを読み込んだときに出る)、最後=ゴールメッセージ。
// hints[1..] の cardCount = そのミッションの前に読み込むカード枚数。
//
// 内容を直したら該当プリセットの rev を1つ上げる。手を入れていない端末では次回起動時に自動で新しい内容に置き換わり、
// ユーザーが編集済みのものは上書きしない。
// 「毎日のミッションを冒険に」がコンセプトなので、せいかつが先。あそびは応用
export const CATEGORY_ORDER = ['せいかつ', 'あそび'];
