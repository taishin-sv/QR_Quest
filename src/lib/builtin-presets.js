// hints[0]=さいしょのミッション、最後=ゴールメッセージ。hints[1..] の cardCount = そのミッションの前に読み込むカード枚数。
export const CATEGORY_ORDER = ['あそび', 'せいかつ'];
export const OWN_CATEGORY = 'じぶんの ぼうけん';

// [絵文字, 文章] の並びから、ゴールまで含むプリセットを組み立てる
function build({ id, name, icon, category, missions, goal }) {
  const hints = [...missions, goal].map(([emoji, text], i) => {
    const h = { emoji, text };
    if (i >= 1) h.cardCount = 1;
    return h;
  });
  return { id, name, icon, category, stageCount: hints.length - 1, hints };
}

